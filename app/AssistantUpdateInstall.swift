import Foundation
import CryptoKit

enum InstallError: LocalizedError {
    /// The installed bundle is no longer the baseline the patch was built from.
    case patchNotApplicable
    case cancelledAuthorization
    case failed(String)

    var errorDescription: String? {
        switch self {
        case .patchNotApplicable: return "补丁与本机安装不一致。"
        case .cancelledAuthorization: return "已取消管理员授权，更新未安装。"
        case .failed(let detail): return detail
        }
    }
}

struct PatchManifest: Decodable {
    struct Entry: Decodable {
        let path: String
        let sha256: String
        let mode: String?
    }
    let version: String
    let from: String
    let bundleId: String?
    let files: [Entry]
    let base: [Entry]
    let remove: [String]
}

/// Turns a verified download into a signed bundle and swaps it in.
///
/// Everything that reads attacker-controlled bytes (archive listing, mounted
/// image, manifest, per-file hashes, signing) happens as the ordinary user,
/// before any privilege is requested. The privileged step only moves two
/// directories inside the installation folder, and the inline script below is
/// generated by the running version so an older installation can still upgrade
/// itself.
///
/// An application installed by dragging it out of the disk image belongs to the
/// user, so the swap runs as that user and never asks for a password. The
/// prompt is only needed when the installation folder cannot be written.
enum UpdateInstaller {
    static let bundleIdentifier = "cn.gdpower.usbkeyassistant"

    static func infoValue(_ app: URL, _ key: String) -> String? {
        guard let data = try? Data(contentsOf: app.appendingPathComponent("Contents/Info.plist")),
              let plist = try? PropertyListSerialization.propertyList(from: data, options: [], format: nil),
              let dictionary = plist as? [String: Any] else { return nil }
        return dictionary[key] as? String
    }
    static func version(of app: URL) -> String? { infoValue(app, "CFBundleShortVersionString") }
    static func identifier(of app: URL) -> String? { infoValue(app, "CFBundleIdentifier") }

    static func sha256(of url: URL) throws -> String {
        guard let handle = try? FileHandle(forReadingFrom: url) else {
            throw InstallError.failed("无法读取 \(url.lastPathComponent)")
        }
        defer { try? handle.close() }
        var hash = SHA256()
        while let chunk = try handle.read(upToCount: 1024 * 1024), !chunk.isEmpty {
            hash.update(data: chunk)
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Staging

    /// Expands the download, verifies it against `plan` and the manifest, and
    /// returns a signed bundle ready to be swapped in.
    static func stage(archive: URL, plan: UpdatePlan, target: URL) throws -> URL {
        let work = FileManager.default.temporaryDirectory
            .appendingPathComponent("USBKeyStage-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: work, withIntermediateDirectories: true,
                                                attributes: [.posixPermissions: 0o700])
        let staged = work.appendingPathComponent("App.app")
        switch plan.kind {
        case .patch:
            try stagePatch(archive: archive, plan: plan, target: target, work: work, staged: staged)
        case .diskImage:
            try stageDiskImage(archive: archive, work: work, staged: staged)
        case .package:
            try stagePackage(archive: archive, work: work, staged: staged)
        }
        guard version(of: staged) == plan.version else {
            throw InstallError.failed("更新包版本号与发布信息不一致")
        }
        guard identifier(of: staged) == bundleIdentifier else {
            throw InstallError.failed("更新包内的应用标识不匹配")
        }
        try sign(staged)
        return staged
    }

    private static func stagePatch(archive: URL, plan: UpdatePlan, target: URL,
                                   work: URL, staged: URL) throws {
        let extract = work.appendingPathComponent("patch")
        try FileManager.default.createDirectory(at: extract, withIntermediateDirectories: true,
                                                attributes: [.posixPermissions: 0o700])
        // Refuse anything that could write outside the staged bundle.
        let listing = try run("/usr/bin/tar", ["-tzf", archive.path], timeout: 120,
                              message: "补丁包无法读取")
        let entries = listing.split(separator: "\n").map(String.init)
        guard !entries.isEmpty else { throw InstallError.failed("补丁包为空") }
        for entry in entries {
            let path = entry.hasPrefix("./") ? String(entry.dropFirst(2)) : entry
            if path.hasSuffix("/") { continue }
            guard path == "patch.json" || path.hasPrefix("Contents/"),
                  !path.contains(".."), !path.hasPrefix("/") else {
                throw InstallError.failed("补丁包包含意外路径")
            }
        }
        try run("/usr/bin/tar", ["-xzf", archive.path, "-C", extract.path], timeout: 180,
                message: "补丁包解压失败")
        guard let data = try? Data(contentsOf: extract.appendingPathComponent("patch.json")),
              let manifest = try? JSONDecoder().decode(PatchManifest.self, from: data) else {
            throw InstallError.failed("补丁包缺少更新清单")
        }
        guard manifest.version == plan.version, manifest.from == plan.installed,
              (manifest.bundleId ?? bundleIdentifier) == bundleIdentifier else {
            throw InstallError.patchNotApplicable
        }
        // Every replaced file must still be the exact bytes the patch was built against.
        for entry in manifest.base {
            guard let current = try? sha256(of: target.appendingPathComponent(entry.path)),
                  current == entry.sha256.lowercased() else {
                throw InstallError.patchNotApplicable
            }
        }
        try run("/usr/bin/ditto", [target.path, staged.path], timeout: 300,
                message: "无法复制当前安装，请检查磁盘空间")
        let fileManager = FileManager.default
        for entry in manifest.files {
            let source = extract.appendingPathComponent(entry.path)
            let destination = staged.appendingPathComponent(entry.path)
            guard let digest = try? sha256(of: source), digest == entry.sha256.lowercased() else {
                throw InstallError.failed("补丁文件校验失败，请重新下载")
            }
            try fileManager.createDirectory(at: destination.deletingLastPathComponent(),
                                            withIntermediateDirectories: true)
            try? fileManager.removeItem(at: destination)
            do {
                try fileManager.copyItem(at: source, to: destination)
            } catch {
                throw InstallError.failed("无法写入更新文件，请检查磁盘空间")
            }
            if let mode = entry.mode, let value = Int(mode, radix: 8) {
                try? fileManager.setAttributes([.posixPermissions: NSNumber(value: value)],
                                               ofItemAtPath: destination.path)
            }
        }
        for path in manifest.remove where path.hasPrefix("Contents/") && !path.contains("..") {
            try? fileManager.removeItem(at: staged.appendingPathComponent(path))
        }
    }

    /// Mounts the disk image read-only and copies the application out of it.
    private static func stageDiskImage(archive: URL, work: URL, staged: URL) throws {
        let mount = work.appendingPathComponent("image")
        try FileManager.default.createDirectory(at: mount, withIntermediateDirectories: true,
                                                attributes: [.posixPermissions: 0o700])
        // The image file itself was already checked against the published digest,
        // so the internal checksum is not worth another full read.
        try run("/usr/bin/hdiutil",
                ["attach", "-readonly", "-nobrowse", "-noautoopen", "-noverify",
                 "-mountpoint", mount.path, archive.path],
                timeout: 180, message: "安装镜像无法打开")
        defer { detach(mount) }
        guard let application = findApplication(in: mount) else {
            throw InstallError.failed("安装镜像内未找到应用")
        }
        guard identifier(of: application) == bundleIdentifier else {
            throw InstallError.failed("安装镜像内的应用标识不匹配")
        }
        try run("/usr/bin/ditto", [application.path, staged.path], timeout: 300,
                message: "无法从安装镜像复制应用，请检查磁盘空间")
    }

    private static func detach(_ mount: URL) {
        let result = ProcessRunner.run(executable: "/usr/bin/hdiutil",
                                       arguments: ["detach", mount.path, "-force"], timeout: 90)
        if result.status != 0 {
            _ = ProcessRunner.run(executable: "/usr/bin/hdiutil",
                                  arguments: ["detach", mount.path], timeout: 30)
        }
    }

    /// Legacy releases shipped a flat package instead of a disk image.
    private static func stagePackage(archive: URL, work: URL, staged: URL) throws {
        let expanded = work.appendingPathComponent("expanded")
        try run("/usr/sbin/pkgutil", ["--expand-full", archive.path, expanded.path], timeout: 300,
                message: "安装包解压失败")
        guard let application = findApplication(in: expanded) else {
            throw InstallError.failed("安装包内未找到应用")
        }
        guard identifier(of: application) == bundleIdentifier else {
            throw InstallError.failed("安装包内的应用标识不匹配")
        }
        try run("/usr/bin/ditto", [application.path, staged.path], timeout: 300,
                message: "无法复制安装包内容，请检查磁盘空间")
    }

    private static func findApplication(in root: URL) -> URL? {
        let keys: Set<URLResourceKey> = [.isDirectoryKey]
        var candidates: [URL] = []
        guard let enumerator = FileManager.default.enumerator(at: root, includingPropertiesForKeys: Array(keys),
                                                             options: [.skipsHiddenFiles]) else { return nil }
        for case let url as URL in enumerator where url.pathExtension == "app" {
            guard (try? url.resourceValues(forKeys: keys))?.isDirectory == true else { continue }
            candidates.append(url)
            enumerator.skipDescendants()
        }
        if candidates.count > 1 {
            candidates = candidates.filter { identifier(of: $0) == bundleIdentifier }
        }
        return candidates.min { $0.pathComponents.count < $1.pathComponents.count }
    }

    private static func sign(_ app: URL) throws {
        try run("/usr/bin/codesign", ["--force", "--deep", "--sign", "-", app.path], timeout: 600,
                message: "更新包签名失败")
        try run("/usr/bin/codesign", ["--verify", "--deep", "--strict", app.path], timeout: 600,
                message: "更新包签名校验失败")
    }

    // MARK: - Install

    /// Whether replacing `target` needs an administrator password.
    ///
    /// A bundle inside a writable, non-sticky directory can be replaced directly,
    /// including a root-owned bundle left by a legacy PKG installation.
    static func replaceNeedsAuthorization(_ target: URL) -> Bool {
        guard getuid() != 0 else { return false }
        guard FileManager.default.isWritableFile(atPath: target.deletingLastPathComponent().path) else {
            return true
        }
        // Renaming a bundle depends on its parent directory, not on who owns
        // its contents. A legacy PKG bundle can therefore be swapped silently
        // in a writable /Applications folder. Sticky directories are different.
        let attributes = try? FileManager.default.attributesOfItem(atPath: target.deletingLastPathComponent().path)
        let mode = (attributes?[.posixPermissions] as? NSNumber)?.intValue ?? 0
        let owner = (try? FileManager.default.attributesOfItem(atPath: target.path))?[.ownerAccountID] as? NSNumber
        guard mode & 0o1000 != 0, let owner else { return false }
        return owner.uint32Value != getuid()
    }

    /// Replaces `target` with `staged`. Returns only after the installed bundle
    /// reports the expected version.
    static func install(staged: URL, target: URL, version expected: String) throws {
        // Written to the temporary directory on purpose: `staged` can live inside
        // a read-only mounted image when the user is moving the application out
        // of it.
        let script = FileManager.default.temporaryDirectory
            .appendingPathComponent("USBKeySwap-\(UUID().uuidString).sh")
        do {
            try swapScript.write(to: script, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: script.path)
        } catch {
            throw InstallError.failed("无法准备安装脚本，请检查磁盘空间")
        }
        defer { try? FileManager.default.removeItem(at: script) }
        let arguments = [script.path, staged.path, target.path, expected,
                         String(getuid()), String(getgid()),
                         FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".Trash/USBKeyPrevious-\(UUID().uuidString).app").path]
        let result: ProcessResult
        if replaceNeedsAuthorization(target) {
            let command = "/bin/sh " + arguments.map(shellQuoted).joined(separator: " ")
            result = ProcessRunner.run(
                executable: "/usr/bin/osascript",
                arguments: ["-e", "do shell script \(appleScriptLiteral(command)) with administrator privileges"],
                timeout: 600, mergeStderr: true)
        } else {
            result = ProcessRunner.run(executable: "/bin/sh", arguments: arguments,
                                       timeout: 300, mergeStderr: true)
        }
        guard result.status == 0, result.failure == nil else {
            let text = result.output.trimmingCharacters(in: .whitespacesAndNewlines)
            if text.contains("-128") || text.localizedCaseInsensitiveContains("cancel") {
                throw InstallError.cancelledAuthorization
            }
            throw InstallError.failed(text.isEmpty ? "安装失败，请重试。" : "安装失败：\(text)")
        }
        guard version(of: target) == expected else {
            throw InstallError.failed("安装后版本校验失败，请从发布页面重新安装")
        }
    }

    /// Read-only running copies update directly into Applications in the same
    /// operation, without first moving and restarting the old version.
    static func updateTarget(for running: URL, root: URL? = nil) -> URL {
        if InstallPath.classify(running).canUpdateInPlace { return running }
        return (root ?? installRoot()).appendingPathComponent(running.lastPathComponent)
    }

    /// Installation folder for a bundle the user is moving out of a disk image:
    /// the shared folder when it is writable, otherwise the user's own one.
    static func installRoot() -> URL {
        let system = URL(fileURLWithPath: "/Applications", isDirectory: true)
        if FileManager.default.isWritableFile(atPath: system.path) { return system }
        let user = FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Applications", isDirectory: true)
        if !FileManager.default.fileExists(atPath: user.path) {
            try? FileManager.default.createDirectory(at: user, withIntermediateDirectories: true)
        }
        return user
    }

    /// Moves a bundle that runs from a read-only location (mounted image or an
    /// AppTranslocation copy) into the installation folder. No authorization is
    /// needed: the user copies a file into a folder they can write to.
    static func relocate(_ source: URL, into root: URL? = nil) throws -> URL {
        let destination = (root ?? installRoot()).appendingPathComponent(source.lastPathComponent)
        if FileManager.default.fileExists(atPath: destination.path) {
            if version(of: destination) == version(of: source) { return destination }
            try install(staged: source, target: destination, version: version(of: source) ?? "")
            return destination
        }
        try run("/usr/bin/ditto", [source.path, destination.path], timeout: 300,
                message: "无法复制应用到“应用程序”文件夹，请检查磁盘空间")
        guard version(of: destination) == version(of: source) else {
            throw InstallError.failed("复制后的应用校验失败，请重新下载安装镜像")
        }
        return destination
    }

    /// Relaunches the installed application once this process has exited, so the
    /// new bundle is not fighting the old one for the bridge port.
    static func relaunchAfterExit(_ target: URL,
                                  waitingFor pid: Int32 = ProcessInfo.processInfo.processIdentifier,
                                  opener: String = "/usr/bin/open") throws {
        let script = "while /bin/kill -0 \(pid) 2>/dev/null; do /bin/sleep 0.2; done; "
            + "\(shellQuoted(opener)) -n \(shellQuoted(target.path))"
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/sh")
        process.arguments = ["-c", script]
        process.standardInput = FileHandle.nullDevice
        process.standardOutput = FileHandle.nullDevice
        process.standardError = FileHandle.nullDevice
        do {
            try process.run()
        } catch {
            throw InstallError.failed("更新已安装，但无法启动自动重启进程：\(error.localizedDescription)")
        }
    }

    // MARK: - Helpers

    @discardableResult
    private static func run(_ tool: String, _ arguments: [String], timeout: TimeInterval,
                            message: String) throws -> String {
        let result = ProcessRunner.run(executable: tool, arguments: arguments, timeout: timeout)
        guard result.status == 0, result.failure == nil else {
            throw InstallError.failed(result.failure ?? message)
        }
        return result.output
    }

    private static func shellQuoted(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
    private static func appleScriptLiteral(_ text: String) -> String {
        "\"" + text
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    /// Generated by the running version on purpose: the installation being
    /// replaced may predate this script entirely.
    ///
    /// `OWNER_UID`/`OWNER_GID` are the identity that started the update. When the
    /// script runs as root they are applied to the new bundle, so an installation
    /// that used to be root-owned becomes user-owned and never prompts again.
    private static let swapScript = """
    #!/bin/sh
    # Move a signed, verified bundle into place. Runs as the user when the
    # installation is user-owned, or as root after a single authorization prompt
    # for legacy root-owned installations.
    set -eu
    STAGED=$1
    TARGET=$2
    VERSION=$3
    OWNER_UID=${4:-}
    OWNER_GID=${5:-}
    TRASH=${6:-}
    fail() { echo "apply-update: $*" >&2; exit 1; }
    [ -d "$STAGED" ] || fail "staged bundle is missing"
    [ ! -e "$TARGET" ] || [ -d "$TARGET" ] || fail "installation path is not a directory"
    if [ -d "$TARGET" ]; then
      IDENTIFIER=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$TARGET/Contents/Info.plist" 2>/dev/null || true)
      [ "$IDENTIFIER" = "cn.gdpower.usbkeyassistant" ] || fail "installed application identifier does not match"
    fi
    STAGE="$TARGET.updating"
    BACKUP="$TARGET.previous.$$"
    rm -rf "$STAGE" 2>/dev/null || true
    if [ -e "$STAGE" ]; then fail "cannot clear the staging path"; fi
    /usr/bin/ditto "$STAGED" "$STAGE" || fail "cannot copy the new bundle"
    if [ "$(/usr/bin/id -u)" = 0 ] && [ -n "$OWNER_UID" ]; then
      /usr/sbin/chown -R "$OWNER_UID:$OWNER_GID" "$STAGE" || fail "cannot hand ownership to the user"
    fi
    /usr/bin/xattr -cr "$STAGE" >/dev/null 2>&1 || true
    # Leftovers from an earlier interrupted run are best effort: they may still
    # be root-owned from a package installation.
    for OLD in "$TARGET.previous" "$TARGET.previous".*; do
      [ -e "$OLD" ] && rm -rf "$OLD" 2>/dev/null || true
    done
    HAD_TARGET=0
    if [ -d "$TARGET" ]; then
      /bin/mv "$TARGET" "$BACKUP" || fail "cannot move the installed bundle aside"
      HAD_TARGET=1
    fi
    if ! /bin/mv "$STAGE" "$TARGET"; then
      if [ "$HAD_TARGET" = 1 ]; then /bin/mv "$BACKUP" "$TARGET" || fail "cannot restore the installed bundle"; fi
      fail "cannot install the new bundle"
    fi
    INSTALLED=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$TARGET/Contents/Info.plist" 2>/dev/null || true)
    if [ "$INSTALLED" != "$VERSION" ]; then
      rm -rf "$TARGET"
      if [ "$HAD_TARGET" = 1 ]; then /bin/mv "$BACKUP" "$TARGET" || fail "cannot restore the installed bundle"; fi
      fail "installed version is $INSTALLED"
    fi
    # A legacy root-owned bundle may be renamed but not recursively deleted.
    # Move it to Trash when possible; never request authorization just to clean
    # up a backup after the new application has already been installed.
    if [ "$HAD_TARGET" = 1 ]; then
      rm -rf "$BACKUP" 2>/dev/null || true
      if [ -e "$BACKUP" ] && [ -n "$TRASH" ] && [ -d "$(/usr/bin/dirname "$TRASH")" ]; then
        /bin/mv "$BACKUP" "$TRASH" 2>/dev/null || true
      fi
    fi
    echo "installed $VERSION"
    """
}
