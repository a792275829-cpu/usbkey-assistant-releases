#!/usr/bin/env python3
"""Build the incremental update archive for the current application build.

The archive holds only the files that differ from a published baseline, plus a
manifest listing the expected hash of every replaced file and of the installation
it was built from. The client verifies both before it touches the installation,
so a patch can never be applied to a bundle it does not match.

Usage:
    python3 scripts/build_patch.py --from <dist/*.dmg | dist/*.pkg | path/to/old.app>
                                    [--out DIR] [--force] [--app path/to/new.app]

Prints one of:
    PATCH=<absolute path>   the archive that should be uploaded
    SKIP=<reason>           nothing worth publishing for this pair of builds
"""

import argparse
import hashlib
import json
import os
import plistlib
import shutil
import subprocess
import sys
import tarfile
import tempfile

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP_NAME = "广东电力USBKey助手"
IDENTIFIER = "cn.gdpower.usbkeyassistant"
# Files that are regenerated by codesign and by the installer itself.
IGNORED_PREFIXES = ("Contents/_CodeSignature/",)
IGNORED_NAMES = (".DS_Store",)
# Above this ratio the archive is not worth a second download next to the image.
MAX_RATIO = 0.6


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    return 1


def app_version(app):
    with open(os.path.join(app, "Contents", "Info.plist"), "rb") as handle:
        return plistlib.load(handle).get("CFBundleShortVersionString", "")


def app_identifier(app):
    with open(os.path.join(app, "Contents", "Info.plist"), "rb") as handle:
        return plistlib.load(handle).get("CFBundleIdentifier", "")


def find_app(root):
    """Locate the application bundle below `root`, shallowest match first."""
    found = []
    for current, directories, _ in os.walk(root):
        for name in directories:
            if not name.endswith(".app"):
                continue
            candidate = os.path.join(current, name)
            if app_identifier(candidate) == IDENTIFIER:
                return candidate
            found.append(candidate)
    if found:
        raise SystemExit(f"error: unexpected bundle identifier under {root}")
    return None


def resolve_app(path, workdir):
    """Return (bundle path, cleanup callable) for a published baseline."""
    if path.endswith(".app"):
        return path, lambda: None
    if path.endswith(".pkg"):
        expanded = os.path.join(workdir, "baseline")
        subprocess.run(["/usr/sbin/pkgutil", "--expand-full", path, expanded], check=True)
        app = find_app(expanded)
        if app is None:
            raise SystemExit(f"error: no application inside {path}")
        return app, lambda: None
    if path.endswith(".dmg"):
        mount = tempfile.mkdtemp(prefix="usbkey-baseline-")
        subprocess.run(["/usr/bin/hdiutil", "attach", "-readonly", "-nobrowse",
                        "-noautoopen", "-noverify", "-mountpoint", mount, path],
                       check=True, stdout=subprocess.DEVNULL)

        def detach():
            subprocess.run(["/usr/bin/hdiutil", "detach", mount, "-force"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            shutil.rmtree(mount, ignore_errors=True)

        app = find_app(mount)
        if app is None:
            detach()
            raise SystemExit(f"error: no application inside {path}")
        return app, detach
    raise SystemExit(f"error: unsupported baseline {path}")


def files(app):
    """Map bundle-relative path -> (sha256, size, mode)."""
    result = {}
    for root, _, names in os.walk(app):
        for name in names:
            full = os.path.join(root, name)
            relative = os.path.relpath(full, app).replace(os.sep, "/")
            if relative.startswith(IGNORED_PREFIXES) or name in IGNORED_NAMES:
                continue
            if os.path.islink(full):
                continue
            digest = hashlib.sha256()
            with open(full, "rb") as handle:
                for block in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(block)
            result[relative] = (digest.hexdigest(), os.path.getsize(full),
                                oct(os.stat(full).st_mode & 0o777)[2:].zfill(4))
    return result


def normalize(info):
    info.uid = 0
    info.gid = 0
    info.uname = ""
    info.gname = ""
    return info


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--from", dest="baseline", required=True,
                        help="published PKG or previously installed .app")
    parser.add_argument("--app", default=os.path.join(PROJECT_DIR, "build", "release", f"{APP_NAME}.app"),
                        help="application bundle that becomes the new version")
    parser.add_argument("--out", default=os.path.join(PROJECT_DIR, "dist"))
    parser.add_argument("--force", action="store_true",
                        help="write the archive even when it is nearly the full size")
    options = parser.parse_args()

    app = options.app
    if not os.path.isdir(app):
        return fail(f"missing build output: {app}")
    version = app_version(app)
    if app_identifier(app) != IDENTIFIER:
        return fail(f"unexpected bundle identifier in {app}")

    with tempfile.TemporaryDirectory() as workdir:
        baseline, detach = resolve_app(options.baseline, workdir)
        try:
            base_version = app_version(baseline)
            if base_version == version:
                return fail("baseline already has the current version")

            new_files = files(app)
            old_files = files(baseline)
            changed = sorted(path for path, meta in new_files.items()
                             if path not in old_files or old_files[path] != meta)
            removed = sorted(path for path in old_files if path not in new_files)
            if not changed and not removed:
                print("SKIP=identical")
                return 0

            manifest = {
                "version": version,
                "from": base_version,
                "bundleId": IDENTIFIER,
                "files": [{"path": path, "sha256": new_files[path][0], "mode": new_files[path][2]}
                          for path in changed],
                # Only files that exist on both sides can be verified before replacing.
                "base": [{"path": path, "sha256": old_files[path][0]}
                         for path in changed if path in old_files],
                "remove": removed,
            }
            manifest_path = os.path.join(workdir, "patch.json")
            with open(manifest_path, "w", encoding="utf-8") as handle:
                json.dump(manifest, handle, ensure_ascii=False, indent=1, sort_keys=True)

            os.makedirs(options.out, exist_ok=True)
            name = f"USBKeyAssistant-{version}-patch-from-{base_version}.tar.gz"
            archive_path = os.path.join(options.out, name)
            with tarfile.open(archive_path, "w:gz") as archive:
                archive.add(manifest_path, arcname="patch.json", filter=normalize)
                for path in changed:
                    archive.add(os.path.join(app, path), arcname=path, filter=normalize)

            # Compare with what the user would otherwise download.
            patch_size = os.path.getsize(archive_path)
            for suffix in ("dmg", "pkg"):
                reference = os.path.join(options.out, f"{APP_NAME}-{version}-apple-silicon.{suffix}")
                if not os.path.exists(reference):
                    continue
                reference_size = os.path.getsize(reference)
                if patch_size > reference_size * MAX_RATIO and not options.force:
                    os.remove(archive_path)
                    print(f"SKIP=patch is {patch_size} bytes of {reference_size} bytes in the {suffix.upper()}")
                    return 0
                break

            digest = hashlib.sha256()
            with open(archive_path, "rb") as handle:
                for block in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(block)
            with open(archive_path + ".sha256", "w", encoding="utf-8") as handle:
                handle.write(f"{digest.hexdigest()}  {name}\n")

            print(f"baseline {base_version} -> {version}: "
                  f"{len(changed)} changed, {len(removed)} removed, {patch_size} bytes",
                  file=sys.stderr)
            print(f"PATCH={archive_path}")
            return 0
        finally:
            detach()


if __name__ == "__main__":
    sys.exit(main())
